/** "A", "A and B", "A, B and C". */
function joinList(names, and) {
  return names.length < 2 ? names.join('') : `${names.slice(0, -1).join(', ')} ${and} ${names[names.length - 1]}`;
}

/** Stored resource text is English ("Hit dice (d8) 0/1"); swap a known name prefix for the language's own. */
function resourceText(v, lang) {
  const known = STRINGS.en.resources;
  const id = Object.keys(known).sort((a, b) => known[b].length - known[a].length).find((k) => v.startsWith(known[k]));
  const out = id === undefined ? v : STRINGS[lang].resources[id] + v.slice(known[id].length);
  return lang === 'fi' ? out.replace(/\((\d)(st|nd|rd)\)/, '($1.)') : out;
}

/** "str 16" → "STR 16". */
function abilityText(v, lang) {
  const [a, n] = v.split(' ');
  return `${STRINGS[lang].abilities[a] ?? a} ${n}`;
}

export function sign(n) { return n >= 0 ? `+${n}` : `${n}`; }

/** "8 + 2 = 10": the die that counted, the bonus, and the total. */
function rollMath(p) {
  if (!p.mod) return `${p.total}`;
  const die = p.total - p.mod;
  return `${die} ${p.mod > 0 ? '+' : '−'} ${Math.abs(p.mod)} = ${p.total}`;
}

